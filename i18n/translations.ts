export const TRANSLATIONS: Record<AppLanguage, Dictionary> = { pl, en, de };

export function translate(
  language: AppLanguage,
  key: string,
  fallback?: string,
  vars?: Record<string, string | number>,
): string {
  let value = TRANSLATIONS[language]?.[key] || TRANSLATIONS.pl[key] || fallback || key;
  if (vars) {
    Object.entries(vars).forEach(([name, replacement]) => {
      value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement));
    });
  }
  return value;
}
